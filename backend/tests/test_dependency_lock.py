"""The pinned dependency files must stay consistent with pyproject.toml.

`requirements.txt` (runtime) and `requirements-dev.txt` (runtime + dev tools) are generated by
`scripts/update_lock.py`. They pin exact versions with hashes so a fresh clone and CI install
the same packages.
"""

import importlib.util
import re
import tomllib
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

BACKEND = Path(__file__).resolve().parents[1]
REPO = BACKEND.parent
RUNTIME_LOCK = BACKEND / "requirements.txt"
DEV_LOCK = BACKEND / "requirements-dev.txt"

_PIN = re.compile(r"^([A-Za-z0-9_.-]+)==([^\s;]+)")


def _pyproject() -> dict:
    return tomllib.loads((BACKEND / "pyproject.toml").read_text(encoding="utf-8"))


def _parse_lock(path: Path) -> dict[str, dict]:
    """Map canonical package name to {"version": str, "hashes": int}."""
    pins: dict[str, dict] = {}
    current: dict | None = None
    for line in path.read_text(encoding="utf-8").splitlines():
        match = _PIN.match(line)
        if match:
            current = {"version": match.group(2), "hashes": 0}
            pins[canonicalize_name(match.group(1))] = current
        elif current is not None and line.strip().startswith("--hash=sha256:"):
            current["hashes"] += 1
    return pins


def _declared(extra: str | None = None) -> list[Requirement]:
    project = _pyproject()["project"]
    specs = project["dependencies"] if extra is None else project["optional-dependencies"][extra]
    return [Requirement(spec) for spec in specs]


@pytest.mark.parametrize("lock", [RUNTIME_LOCK, DEV_LOCK], ids=lambda p: p.name)
def test_every_package_is_pinned_exactly_with_hashes(lock: Path) -> None:
    pins = _parse_lock(lock)

    assert pins, f"{lock.name} has no pinned packages"
    assert all(entry["hashes"] >= 1 for entry in pins.values()), "a package has no hash"


@pytest.mark.parametrize("lock", [RUNTIME_LOCK, DEV_LOCK], ids=lambda p: p.name)
def test_lock_files_contain_no_local_paths_or_editable_installs(lock: Path) -> None:
    text = lock.read_text(encoding="utf-8")

    for forbidden in (
        "-e ",
        "file:",
        "git+",
        "http://",
        "https://",
        "C:\\",
        "D:\\",
        "/Users/",
        "/home/",
    ):
        assert forbidden not in text, f"{lock.name} contains {forbidden!r}"


def test_runtime_dependencies_are_locked_within_their_declared_ranges() -> None:
    pins = _parse_lock(RUNTIME_LOCK)

    for requirement in _declared():
        name = canonicalize_name(requirement.name)
        assert name in pins, (
            f"{requirement.name} is declared but not locked; run scripts/update_lock.py"
        )
        assert requirement.specifier.contains(pins[name]["version"], prereleases=True), (
            f"locked {requirement.name}=={pins[name]['version']} violates "
            f"'{requirement.specifier}'; run scripts/update_lock.py"
        )


def test_dev_lock_covers_runtime_and_dev_dependencies() -> None:
    pins = _parse_lock(DEV_LOCK)

    for requirement in [*_declared(), *_declared("dev")]:
        name = canonicalize_name(requirement.name)
        assert name in pins, f"{requirement.name} missing from requirements-dev.txt"
        assert requirement.specifier.contains(pins[name]["version"], prereleases=True), (
            f"locked {requirement.name}=={pins[name]['version']} violates '{requirement.specifier}'"
        )


def test_runtime_lock_is_a_subset_of_the_dev_lock_with_equal_versions() -> None:
    runtime, dev = _parse_lock(RUNTIME_LOCK), _parse_lock(DEV_LOCK)

    for name, entry in runtime.items():
        assert name in dev and dev[name]["version"] == entry["version"], name


def test_dev_tools_are_not_shipped_in_the_runtime_lock() -> None:
    runtime = _parse_lock(RUNTIME_LOCK)

    for requirement in _declared("dev"):
        assert canonicalize_name(requirement.name) not in runtime


@pytest.mark.parametrize("lock", [RUNTIME_LOCK, DEV_LOCK], ids=lambda p: p.name)
def test_lock_was_generated_for_every_platform_and_the_minimum_python(lock: Path) -> None:
    header = "\n".join(lock.read_text(encoding="utf-8").splitlines()[:3])
    minimum = _pyproject()["project"]["requires-python"].lstrip(">=")

    assert "--universal" in header and "--generate-hashes" in header
    assert f"--python-version {minimum}" in header


# --------------------------------------------------------------------- refresh script


def _load_update_script():
    spec = importlib.util.spec_from_file_location(
        "update_lock", REPO / "scripts" / "update_lock.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_refresh_script_uses_the_same_minimum_python_as_pyproject() -> None:
    script = _load_update_script()
    minimum = _pyproject()["project"]["requires-python"].lstrip(">=")

    assert script.MIN_PYTHON == minimum
    assert [name for name, _ in script.JOBS] == ["requirements.txt", "requirements-dev.txt"]


def test_refresh_script_explains_how_to_get_uv_when_missing(monkeypatch, capsys) -> None:
    script = _load_update_script()
    monkeypatch.setattr(script, "uv_command", lambda: None)

    assert script.main([]) == 2
    assert "python -m pip install uv" in capsys.readouterr().err


def test_refresh_script_builds_the_documented_commands(monkeypatch) -> None:
    script = _load_update_script()
    calls: list[list[str]] = []

    class Done:
        returncode = 0

    monkeypatch.setattr(script, "uv_command", lambda: ["uv"])
    monkeypatch.setattr(
        script.subprocess, "run", lambda cmd, cwd, check: calls.append(cmd) or Done()
    )

    assert script.main(["--upgrade"]) == 0
    runtime, dev = calls
    assert runtime[:4] == ["uv", "pip", "compile", "pyproject.toml"]
    assert "--extra" not in runtime and runtime[runtime.index("-o") + 1] == "requirements.txt"
    assert (
        dev[dev.index("--extra") + 1] == "dev"
        and dev[dev.index("-o") + 1] == "requirements-dev.txt"
    )
    assert all("--upgrade" in c and "--generate-hashes" in c and "--universal" in c for c in calls)


def test_refresh_script_stops_at_the_first_failure(monkeypatch) -> None:
    script = _load_update_script()
    calls: list[list[str]] = []

    class Failed:
        returncode = 7

    monkeypatch.setattr(script, "uv_command", lambda: ["uv"])
    monkeypatch.setattr(
        script.subprocess, "run", lambda cmd, cwd, check: calls.append(cmd) or Failed()
    )

    assert script.main([]) == 7
    assert len(calls) == 1
